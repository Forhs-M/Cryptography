import matplotlib.pyplot as plt

# is_prime : Checks if a number is prime
# num : Integer number
# Retuns True if the number is a prime one, False if not
 
def is_prime(num):
    if num == 1 | num == 0:
        return False
    for i in range(2, int(num**0.5 )+ 1):
        if num % i == 0 :
            return False
    return True

# data_collect : Generates a sequence using the recurrence relation:
#                x_{i+1} = (5 * x_i + 3) mod 2^10
# num : The initial number (x_0) to start the sequence from
# Returns list containing the first 150 prime numbers found in the sequence

def data_collect(num):
    ind = 0
    data = []
    while ind < 150:
        num = (5*num + 3) % (2**10)
        if is_prime(num):
            ind += 1
            data.append(num)
    return data


# Example usage of data_collect for x_0 = 1

data = data_collect(1)

# Create the histogram

plt.hist(data, bins = 10, edgecolor = 'black')

# Add labels and title

plt.title("Histogram of Prime Numbers Generated by: data_collect() ")
plt.xlabel("Value")
plt.ylabel("Frequency")

# Show the plot

plt.show()